#!/usr/bin/env python3
"""Export pipeline-generated manuscript figures into a stable generated tree.

The computational stages keep their run-local outputs. This script is the
single code path that curates those outputs into manuscript Figures 2-4 and
supplementary generated figures.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import shutil
from pathlib import Path
from typing import Any


FIGURE_EXTS = {".png", ".svg", ".pdf"}
MANIFEST_FIELDS = [
    "section",
    "figure_id",
    "panel_id",
    "title",
    "source_rel",
    "destination_rel",
    "status",
]


def _rel(path: Path, root: Path) -> str:
    return path.resolve().relative_to(root.resolve()).as_posix()


def _format_template(value: str, *, run_name: str) -> str:
    return value.replace("{RUN_NAME}", run_name)


def _slug(value: str) -> str:
    value = value.strip().lower()
    value = re.sub(r"[^a-z0-9]+", "_", value)
    return value.strip("_") or "panel"


def _load_registry(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as f:
        registry = json.load(f)
    figures = registry.get("figures", [])
    if any(fig.get("id") == "figure_1" and fig.get("pipeline_generated", True) for fig in figures):
        raise ValueError("Figure 1 is non-pipeline and must not be listed as a generated manuscript figure.")
    return registry


def _write_manifest(path: Path, rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=MANIFEST_FIELDS)
        writer.writeheader()
        writer.writerows(rows)


def _copy_or_check(src: Path, dst: Path, *, verify_only: bool) -> str:
    if not src.is_file():
        return "missing_source"
    if verify_only:
        return "ok" if dst.is_file() else "missing_destination"
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    return "copied"


def _source_candidates(panel: dict[str, Any], *, run_name: str) -> list[Path]:
    value = panel["source"]
    if isinstance(value, str):
        values = [value]
    else:
        values = list(value)
    return [Path(_format_template(str(item), run_name=run_name)) for item in values]


def _resolve_panel_source(panel: dict[str, Any], *, repo_root: Path, run_name: str) -> tuple[Path, Path, list[Path]]:
    candidates = _source_candidates(panel, run_name=run_name)
    for source_rel in candidates:
        source_abs = (repo_root / source_rel).resolve()
        if source_abs.is_file():
            return source_rel, source_abs, candidates
    source_rel = candidates[0]
    return source_rel, (repo_root / source_rel).resolve(), candidates


def _panel_destination(fig_dir: Path, panel: dict[str, Any], src: Path) -> Path:
    panel_id = str(panel["id"])
    title = panel.get("title") or panel_id
    return fig_dir / "panels" / f"{_slug(panel_id)}_{_slug(title)}{src.suffix.lower()}"


def _iter_supplement_sources(
    registry: dict[str, Any],
    *,
    repo_root: Path,
    run_name: str,
    main_sources: set[Path],
) -> list[Path]:
    sources: set[Path] = set()
    exclude_globs = [_format_template(p, run_name=run_name) for p in registry.get("exclude_globs", [])]
    for pattern in registry.get("supplement_globs", []):
        pattern = _format_template(pattern, run_name=run_name)
        for src in repo_root.glob(pattern):
            if not src.is_file():
                continue
            if src.suffix.lower() not in FIGURE_EXTS:
                continue
            rel = src.relative_to(repo_root)
            if any(rel.match(excl) for excl in exclude_globs):
                continue
            if src.resolve() in main_sources:
                continue
            sources.add(src.resolve())
    return sorted(sources)


def _write_readme(manuscript_figures_dir: Path, *, run_name: str, rows: list[dict[str, str]]) -> None:
    lines = [
        "# Manuscript Figures",
        "",
        "This directory is generated by `scripts/export_manuscript_figures.py`.",
        "It contains only pipeline-generated manuscript Figures 2-4 and their component panels.",
        "Figure 1 is a non-pipeline schematic supplied separately under `final_figures/`.",
        "",
        f"Run name: `{run_name}`",
        "",
        "## Main Figures",
        "",
    ]
    for row in rows:
        if row["section"] != "main":
            continue
        lines.append(
            f"- `{row['figure_id']}` panel `{row['panel_id']}`: "
            f"`{row['destination_rel']}` from `{row['source_rel']}`"
        )
    lines.append("")
    manuscript_figures_dir.mkdir(parents=True, exist_ok=True)
    (manuscript_figures_dir / "README.md").write_text("\n".join(lines), encoding="utf-8")


def export_manuscript_figures(
    *,
    repo_root: Path,
    registry_path: Path,
    run_name: str,
    manuscript_dir: Path,
    clean: bool,
    verify_only: bool,
) -> int:
    repo_root = repo_root.resolve()
    manuscript_dir = manuscript_dir.resolve()
    registry = _load_registry(registry_path)

    manuscript_figures_dir = manuscript_dir / "figures"
    supplement_dir = manuscript_dir / "supplement" / "figures"
    if clean and not verify_only:
        for path in (manuscript_figures_dir, supplement_dir):
            if path.exists():
                shutil.rmtree(path)

    rows: list[dict[str, str]] = []
    main_sources: set[Path] = set()
    failures: list[str] = []

    for figure in registry.get("figures", []):
        fig_id = str(figure["id"])
        fig_dir = manuscript_figures_dir / str(figure["output_dir"])
        for panel in figure.get("panels", []):
            src_rel, src, candidates = _resolve_panel_source(panel, repo_root=repo_root, run_name=run_name)
            dst = _panel_destination(fig_dir, panel, src)
            status = _copy_or_check(src, dst, verify_only=verify_only)
            if status.startswith("missing"):
                choices = ", ".join(p.as_posix() for p in candidates)
                failures.append(f"{fig_id} panel {panel['id']}: {status} (tried: {choices})")
            if src.is_file():
                main_sources.add(src.resolve())
            rows.append(
                {
                    "section": "main",
                    "figure_id": fig_id,
                    "panel_id": str(panel["id"]),
                    "title": str(panel.get("title", "")),
                    "source_rel": src_rel.as_posix(),
                    "destination_rel": _rel(dst, repo_root) if dst.exists() or not verify_only else (dst.relative_to(repo_root).as_posix() if dst.is_relative_to(repo_root) else dst.as_posix()),
                    "status": status,
                }
            )

    supplement_rows: list[dict[str, str]] = []
    for src in _iter_supplement_sources(registry, repo_root=repo_root, run_name=run_name, main_sources=main_sources):
        source_rel = src.relative_to(repo_root)
        dst = supplement_dir / source_rel
        status = _copy_or_check(src, dst, verify_only=verify_only)
        if status.startswith("missing"):
            failures.append(f"supplement: {status} ({source_rel})")
        supplement_rows.append(
            {
                "section": "supplement",
                "figure_id": "supplement",
                "panel_id": "",
                "title": source_rel.stem,
                "source_rel": source_rel.as_posix(),
                "destination_rel": dst.relative_to(repo_root).as_posix() if dst.is_relative_to(repo_root) else dst.as_posix(),
                "status": status,
            }
        )

    if not verify_only:
        _write_manifest(manuscript_figures_dir / "manifest.csv", rows)
        _write_manifest(supplement_dir / "manifest.csv", supplement_rows)
        _write_readme(manuscript_figures_dir, run_name=run_name, rows=rows)
    else:
        if not (manuscript_figures_dir / "manifest.csv").is_file():
            failures.append(f"missing manifest: {(manuscript_figures_dir / 'manifest.csv').relative_to(repo_root)}")
        if not (supplement_dir / "manifest.csv").is_file():
            failures.append(f"missing manifest: {(supplement_dir / 'manifest.csv').relative_to(repo_root)}")

    if failures:
        for failure in failures:
            print(f"[manuscript-figures] ERROR {failure}")
        return 1

    action = "verified" if verify_only else "exported"
    print(
        f"[manuscript-figures] {action} {len(rows)} main panels "
        f"and {len(supplement_rows)} supplementary figures under {manuscript_dir}"
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Export manuscript Figures 2-4 and supplementary figures.")
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--registry", type=Path, default=None)
    parser.add_argument("--run-name", default="eval_run")
    parser.add_argument("--manuscript-dir", type=Path, default=None)
    parser.add_argument("--clean", action="store_true", help="Remove generated manuscript figure directories before export.")
    parser.add_argument("--verify-only", action="store_true", help="Verify existing exported files without copying.")
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    registry = args.registry or (repo_root / "config" / "manuscript_figures.json")
    manuscript_dir = args.manuscript_dir or (repo_root / "outputs" / "manuscript")

    return export_manuscript_figures(
        repo_root=repo_root,
        registry_path=registry.resolve(),
        run_name=args.run_name,
        manuscript_dir=manuscript_dir,
        clean=args.clean,
        verify_only=args.verify_only,
    )


if __name__ == "__main__":
    raise SystemExit(main())
