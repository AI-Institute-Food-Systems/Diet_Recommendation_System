#!/usr/bin/env python3
"""
Quick pipeline status check: which stage outputs exist for a run.

Generated outputs are intentionally ignored by Git, so a clean clone is expected
to show pending run stages until the Makefile pipeline is executed.
"""

import glob as glob_module
import os
import sys
from pathlib import Path
from typing import Dict


RUN_NAME = os.environ.get("RUN_NAME", "eval_run")


def check_file_exists(pattern: str) -> bool:
    """Return True if at least one path matches pattern or the literal path exists."""
    if "*" in pattern or "?" in pattern or "[" in pattern:
        return len(glob_module.glob(pattern)) > 0
    return Path(pattern).exists()


def _step(description: str, required: list[str], optional: list[str] | None = None) -> Dict:
    missing_required = [path for path in required if not check_file_exists(path)]
    missing_optional = [path for path in (optional or []) if not check_file_exists(path)]
    return {
        "completed": not missing_required,
        "description": description,
        "missing_outputs": missing_required,
        "missing_optional": missing_optional,
    }


def check_pipeline_status() -> Dict[str, Dict]:
    """Check source prerequisites and the outputs of each pipeline stage."""

    output_root = "outputs"
    run_root = f"{output_root}/runs/{RUN_NAME}"
    cluster_root = f"{output_root}/clustering"
    manuscript_root = f"{output_root}/manuscript"
    return {
        "source_tree": _step(
            "Tracked source/config/docs/tests needed to regenerate outputs",
            [
                "Makefile",
                "requirements.txt",
                "config/cvae_multi_meal.json",
                "config/manuscript_figures.json",
                "cli/run_multi_meal_cvae.py",
                "cli/evaluate.py",
                "experiments/analyze_meal_substitutions.py",
                "scripts/export_manuscript_figures.py",
                "tests/test_smoke.py",
            ],
        ),
        "preprocessing": _step(
            "Data preprocessing and prototype mapping",
            [
                "data/processed/real_meals/dataframes/breakfast_bci_filtered.pkl",
                "data/processed/real_meals/dataframes/lunch_bci_filtered.pkl",
                "data/processed/real_meals/dataframes/dinner_bci_filtered.pkl",
                "data/mappings/food_to_prototype.pkl",
            ],
        ),
        "clustering": _step(
            "Meal clustering analysis generated by make clustering",
            [
                f"{cluster_root}/breakfast/cluster_*_training_data.units.json",
                f"{cluster_root}/lunch/cluster_*_training_data.units.json",
                f"{cluster_root}/dinner/cluster_*_training_data.units.json",
                f"{cluster_root}/combined_tsne_landscape.svg",
                f"{cluster_root}/breakfast_dot_matrix.svg",
                f"{cluster_root}/lunch_dot_matrix.svg",
                f"{cluster_root}/dinner_dot_matrix.svg",
            ],
        ),
        "cvae_training": _step(
            f"CVAE model artifacts for RUN_NAME={RUN_NAME}",
            [
                f"{run_root}/model",
                f"{run_root}/presence_only_model",
            ],
        ),
        "evaluation": _step(
            f"Evaluation tables, data exports, and figures for RUN_NAME={RUN_NAME}",
            [
                f"{run_root}/data_exports/",
                f"{run_root}/figures/",
                f"{run_root}/tables/cluster_counts.csv",
            ],
        ),
        "substitutions": _step(
            f"Substitution, theta-sweep and Figure 4A outputs for RUN_NAME={RUN_NAME}",
            [
                f"{run_root}/substitutions_k3/figures_theta_sweep/optimal_theta_by_k.txt",
                f"{run_root}/substitutions_k3/figures_theta_sweep/figure_cost_benefit_points_by_theta_and_k.svg",
                f"{run_root}/substitutions_k3/figures_theta_sweep/figure_category_scatter_plus_heatmap_k123.svg",
                f"{run_root}/substitutions_k3/figure4a/fixed_meal_composition.svg",
            ],
        ),
        "manuscript_exports": _step(
            "Manuscript figures and headline-numbers log",
            [
                f"{manuscript_root}/figures/manifest.csv",
                f"{manuscript_root}/supplement/figures/manifest.csv",
                f"{output_root}/final_results_log.txt",
            ],
        ),
        "supplementary_optional": _step(
            f"Supplementary analyses for RUN_NAME={RUN_NAME} (make supplementary)",
            [],
            [
                f"{run_root}/supplementary/cluster_stability/dinner/stability_summary.csv",
                f"{run_root}/supplementary/primary_outcomes_cis/rdi_alignment_cis.csv",
                f"{run_root}/supplementary/cost_sensitivity/table_S_COST2_grocery_only.csv",
                f"{run_root}/supplementary/substitution_outcomes/substitution_counts.csv",
            ],
        ),
    }


def print_status(status: Dict[str, Dict]):
    """Print the pipeline status in a formatted way."""

    print("=" * 80)
    print("MEAL RECOMMENDATION PIPELINE STATUS")
    print("=" * 80)

    for step, info in status.items():
        status_icon = "✓" if info["completed"] else "✗"
        status_text = "COMPLETED" if info["completed"] else "PENDING"

        print(f"\n{status_icon} {step.upper()}: {status_text}")
        print(f"   {info['description']}")

        if not info["completed"] and info["missing_outputs"]:
            print("   Missing outputs:")
            for output in info["missing_outputs"]:
                print(f"     - {output}")
        if info.get("missing_optional"):
            print("   Optional outputs not present:")
            for output in info["missing_optional"]:
                print(f"     - {output}")

    print("\n" + "=" * 80)

    # Summary
    completed_count = sum(1 for info in status.values() if info["completed"])
    total_count = len(status)

    print(f"\nSUMMARY: {completed_count}/{total_count} steps completed")

    if completed_count == total_count:
        print("Pipeline is complete.")
    elif completed_count == 0:
        print("Pipeline has not been started yet.")
    else:
        print("Pipeline is in progress...")

    print("\nNext steps:")
    if completed_count < total_count:
        print(f"   Run the full pipeline: make reproduce RUN_NAME={RUN_NAME}")
        print("   Or run per stage: make preprocess | clustering | cvae_train | eval | substitutions | "
              "theta_sweep | figure4a | manuscript-figures | manuscript-numbers")
    else:
        print("   All required tracked stages have expected local outputs.")


def main():
    """Main entry point."""
    if len(sys.argv) > 1 and sys.argv[1] in ["-h", "--help"]:
        print("Usage: python3 scripts/check_pipeline_status.py")
        print("Quick check of pipeline status (run from repository root).")
        return 0

    repo_root = Path(__file__).resolve().parents[1]
    os.chdir(repo_root)

    try:
        status = check_pipeline_status()
        print_status(status)
        return 0
    except Exception as e:
        print(f"Error checking pipeline status: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
